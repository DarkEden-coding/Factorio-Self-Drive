#!/usr/bin/env python3
"""Build the deterministic Lua student and pinned simulator geometry modules."""
import argparse
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT = ROOT / 'python/runs/students/path-stop/path-stop.json'
PATHFINDER_HASH = 'a38878852fab9d85'


def lua(value):
    if value is None:
        return 'nil'
    if isinstance(value, bool):
        return str(value).lower()
    if isinstance(value, str):
        return json.dumps(value)
    if isinstance(value, (float, int)):
        if not math.isfinite(value):
            raise ValueError('non-finite model value')
        return repr(value)
    if isinstance(value, list):
        return '{' + ','.join(map(lua, value)) + '}'
    return '{' + ','.join('[' + lua(k) + ']=' + lua(v) for k, v in value.items()) + '}'


def build(model_path, destination):
    model = json.loads(model_path.read_text())
    student_map = model.get('map')
    if (model['format'] != 'fsim-student-v2' or model['spec_hash'] != PATHFINDER_HASH
            or not student_map or student_map.get('pathfinder_spec_hash') != PATHFINDER_HASH
            or student_map.get('route_source') != 'pathfinder' or not model.get('route')
            or model['decision_ticks'] != 4 or model['obs']['size'] != 135 or model['ray_conv']):
        raise ValueError('expected the pathfinder-route map student (path-stop), interval 4')
    size = student_map['size']
    if size != 135 + 3 * student_map['cells'] ** 2:
        raise ValueError('map dimensions')
    if len(model['normalizer']['mean']) != size or len(model['normalizer']['std']) != size:
        raise ValueError('normalizer dimensions')
    if any(v <= 0 for v in model['normalizer']['std']):
        raise ValueError('normalizer std must be positive')
    convs, channels, cells = [], 3, student_map['cells']
    for layer in student_map['conv']:
        if layer['in'] != channels or layer['size_in'] != cells or len(layer['weight']) != layer['out']:
            raise ValueError('map conv dimensions')
        flat = [w for o in layer['weight'] for c in o for row in c for w in row]
        if len(flat) != layer['out'] * layer['in'] * layer['kernel'] ** 2:
            raise ValueError('map conv weight dimensions')
        convs.append({**layer, 'weight': flat})
        channels, cells = layer['out'], layer['size_out']
    # Dense input: rays, route, other student features, then the map conv output.
    size = 135 + (channels * cells * cells if convs else 3 * student_map['cells'] ** 2)
    layers = []
    for layer in model['dense']:
        if layer['in'] != size or len(layer['weight']) != layer['out'] or len(layer['bias']) != layer['out']:
            raise ValueError('dense layer dimensions')
        if any(len(row) != size for row in layer['weight']):
            raise ValueError('dense row dimensions')
        layers.append({**layer, 'weight': [w for row in layer['weight'] for w in row]})
        size = layer['out']
    if size != 9:
        raise ValueError('expected nine actions')
    model = {**model, 'map': {**student_map, 'conv': convs}}
    out = {**model, 'dense': layers}
    destination.mkdir(parents=True, exist_ok=True)
    (destination / 'weights.lua').write_text('-- Generated by scripts/build-autodrive-weights.py. Do not edit.\nreturn ' + lua(out) + '\n')
    data = json.loads((ROOT / 'data/prototypes.json').read_text())
    geometry = {'vehicles': {v['name']: v for v in data['vehicles']},
                'cliffs': data['cliffs']['orientations'],
                'nest_radius': data['physics']['nest_penalty_radius']}
    (destination / 'geometry-data.lua').write_text('-- Generated from data/prototypes.json.\nreturn ' + lua(geometry) + '\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--model', type=Path, default=DEFAULT)
    parser.add_argument('--output', type=Path, default=ROOT / 'mod/fsim-autodrive')
    args = parser.parse_args()
    build(args.model, args.output)
