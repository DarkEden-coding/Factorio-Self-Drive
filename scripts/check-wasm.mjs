import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { performance } from 'node:perf_hooks';
import init, { Sim } from '../crates/fsim-wasm/pkg/fsim_wasm.js';

const bytes = await readFile(new URL('../crates/fsim-wasm/pkg/fsim_wasm_bg.wasm', import.meta.url));
await init({ module_or_path: bytes });
const config = JSON.stringify({ vehicle: 'car', fuel: 'coal' });
const map = await readFile(new URL('../crates/fsim-core/tests/fixtures/nauvis-origin.fsmap', import.meta.url));
const start = performance.now();
const sim = new Sim(config, map);
const loadMs = performance.now() - start;
const info = JSON.parse(sim.map_info());
assert.equal(info.width, 128);
assert.equal(info.height, 128);
assert.equal(info.x_min, -64);
assert.equal(info.seed, 12345);
const state = JSON.parse(sim.vehicle_state());
assert.equal(state.kind, 'car');
assert.equal(state.fuel, 'coal');
assert.equal(state.health, 450);
assert.equal(state.tick, 0);
assert.equal(state.last_collision, null);
const prototypes = JSON.parse(await readFile(new URL('../data/prototypes.json', import.meta.url), 'utf8'));
assert.deepEqual(state.collision_box, prototypes.vehicles.find(v => v.name === 'car').collision_box);
const tiles = sim.tiles();
const resources = sim.resources();
assert.ok(tiles instanceof Uint8Array);
assert.ok(resources instanceof Uint8Array);
assert.equal(tiles.length, 128*128);
assert.equal(resources.length, tiles.length);
const tilePalette = JSON.parse(sim.tile_palette());
const resourcePalette = JSON.parse(sim.resource_palette());
assert.equal(tilePalette.length, 21);
assert.equal(resourcePalette.length, prototypes.resources.length + 1);
for (const id of tiles) assert.equal(tilePalette[id].id, id);
for (const id of resources) assert.equal(resourcePalette[id].id, id);
const entities = JSON.parse(sim.entities_in_rect(-256,-256,256,256));
assert.ok(entities.length > 0);
assert.ok(entities.every(e => ['cliff','nest','rock','tree'].includes(e.kind)));
assert.equal(info.name, 'nauvis-seed-12345-origin');
assert.deepEqual(info.source_offset, [0,0]);
const spec = JSON.parse(sim.observation_spec());
assert.deepEqual(spec, { local_size:64,coarse_size:32,coarse_cell_tiles:8,
    channels:['blocked','cliff','tree','rock','water','nest_zone','friction','target'] });
const local = sim.observation_local();
const coarse = sim.observation_coarse();
assert.ok(local instanceof Float32Array);
assert.ok(coarse instanceof Float32Array);
assert.equal(local.length,8*64*64);
assert.equal(coarse.length,8*32*32);
assert.ok(local.every(Number.isFinite));
assert.ok(coarse.every(Number.isFinite));
assert.equal(JSON.parse(sim.target_state()),null);
sim.set_target(10,-4);
assert.equal(JSON.parse(sim.target_state()).radius,3);
sim.clear_target();
assert.equal(JSON.parse(sim.target_state()),null);
assert.deepEqual(JSON.parse(sim.vehicle_list()).map(v=>v.name),['car','tank']);
assert.equal(JSON.parse(sim.fuel_list()).length,5);
const twin = new Sim(config, map);
sim.step(1,1,400);
twin.step(1,1,400);
assert.deepEqual(JSON.parse(sim.vehicle_state()),JSON.parse(twin.vehicle_state()));
const position = JSON.parse(sim.vehicle_state());
sim.set_vehicle('tank','nuclear-fuel');
const tank = JSON.parse(sim.vehicle_state());
assert.equal(tank.x, position.x);
assert.equal(tank.y, position.y);
assert.equal(tank.orientation, position.orientation);
assert.equal(tank.health,2000);
assert.equal(tank.speed,0);
sim.set_target(2,2);
sim.reset();
assert.equal(JSON.parse(sim.vehicle_state()).tick,0);
assert.equal(JSON.parse(sim.target_state()),null);
const revision = sim.map_revision();
sim.load_map(map);
assert.ok(sim.map_revision()>revision);
assert.equal(sim.tiles().length,128*128);
assert.throws(()=>sim.step(5,0,1));
assert.throws(()=>sim.step(1,0,0));
assert.throws(()=>sim.set_vehicle('unknown','coal'));
assert.throws(()=>sim.set_target(NaN,0));
assert.throws(()=>sim.entities_in_rect(1,1,0,0));
assert.throws(()=>new Sim('{bad json', map));
assert.throws(()=>new Sim(JSON.stringify({seed:7}), map));
assert.throws(()=>new Sim(config, new Uint8Array()));
const beforeImport = sim.map_revision();
const beforeTiles = sim.tile_revision();
sim.set_target(5,5);
const report = JSON.parse(sim.load_map(map));
assert.equal(report.name, 'nauvis-seed-12345-origin');
assert.deepEqual(report.offset, [0,0]);
assert.deepEqual(report.warnings, []);
assert.ok(report.warnings.every(w => typeof w === 'string'));
assert.ok(JSON.parse(sim.entities_in_rect(-64,-64,64,64)).some(e => e.name === 'tree-02-red'));
assert.equal(JSON.parse(sim.map_info()).width,128);
assert.deepEqual(JSON.parse(sim.map_info()).source_offset,[0,0]);
assert.equal(sim.tiles().length,128*128);
assert.equal(JSON.parse(sim.vehicle_state()).tick,0);
assert.equal(JSON.parse(sim.target_state()),null);
assert.ok(sim.map_revision()>beforeImport);
assert.ok(sim.tile_revision()>beforeTiles);
const importedState = sim.vehicle_state();
assert.throws(()=>sim.load_map(new Uint8Array()));
assert.equal(sim.vehicle_state(), importedState);
// RL additions (docs/rl.md, "WASM additions").
const rlSpec = JSON.parse(sim.spec());
assert.equal(rlSpec.spec_hash.length, 16);
assert.deepEqual(rlSpec.local_shape, [8,64,64]);
assert.deepEqual(rlSpec.coarse_shape, [8,32,32]);
assert.equal(rlSpec.vector_features.length, rlSpec.vector_size);
assert.throws(()=>sim.policy_local());
assert.throws(()=>sim.decide(4));
assert.equal(JSON.parse(sim.episode_state()), null);
const sampleRequest = JSON.stringify({ seed: 3, min_distance: 12, max_distance: 40, max_tortuosity: 1.5, radius: 3 });
const episode = JSON.parse(sim.sample_episode(sampleRequest));
assert.deepEqual(JSON.parse(sim.sample_episode(sampleRequest)), episode);
assert.ok(episode.optimal_distance >= 12 && episode.optimal_distance <= 40);
assert.equal(episode.mode, 'reactive');
assert.equal(episode.decision_ticks, 4);
assert.equal(JSON.parse(sim.target_state()).x, episode.target.x);
const policyLocal = sim.policy_local();
const policyCoarse = sim.policy_coarse();
const policyVector = sim.policy_vector();
assert.ok(policyLocal instanceof Uint8Array && policyLocal.length === 8*64*64);
assert.ok(policyCoarse instanceof Uint8Array && policyCoarse.length === 8*32*32);
assert.ok(policyVector instanceof Float32Array && policyVector.length === rlSpec.vector_size);
assert.ok(policyVector.every(Number.isFinite));
const field = JSON.parse(sim.distance_field());
const fieldValues = sim.distance_field_values();
assert.ok(fieldValues instanceof Float32Array);
assert.equal(fieldValues.length, field.width * field.height);
const baseline = sim.baseline_path();
assert.ok(baseline instanceof Float32Array && baseline.length >= 4 && baseline.length % 2 === 0);
assert.ok(Math.abs(baseline.at(-2) - episode.target.x) < 1e-4 && Math.abs(baseline.at(-1) - episode.target.y) < 1e-4);
const predicted = sim.predict_path(new Uint8Array(24).fill(7));
assert.ok(predicted instanceof Float32Array && predicted.length % 2 === 0 && predicted.length <= 48);
assert.deepEqual(JSON.parse(sim.vehicle_state()).x, episode.start.x);
const planned = sim.plan_waypoints(new Float32Array([0, 10, 0, 500]));
assert.equal(planned.length, 4);
const vs = JSON.parse(sim.vehicle_state());
assert.ok(Math.abs(Math.hypot(planned[2] - vs.x, planned[3] - vs.y) - 100) < 1e-3);
// Drive the baseline with follow_path, replanning like the env.
const actions = [];
let decision;
let waypoints = sim.baseline_path();
for (let i = 0; i < 2000; i++) {
  decision = JSON.parse(sim.follow_path(waypoints));
  actions.push(decision.action);
  const terms = Object.values(decision.terms).reduce((a, b) => a + b, 0);
  assert.ok(Math.abs(terms - decision.reward) < 1e-9);
  if (decision.done) break;
  if (decision.replan) waypoints = sim.baseline_path();
}
assert.equal(decision.status, 'success');
const finished = JSON.parse(sim.episode_state());
assert.equal(finished.status, 'success');
assert.equal(finished.decisions, actions.length);
assert.ok(finished.reward.success > 0);
assert.throws(()=>sim.decide(4));
const finalState = sim.vehicle_state();
// Replay: an episode JSON (or record) restarts the same episode; decide() reproduces it.
JSON.parse(sim.start_episode(JSON.stringify({ ...episode, actions })));
for (const a of actions) sim.decide(a);
assert.equal(sim.vehicle_state(), finalState);
assert.deepEqual(JSON.parse(sim.episode_state()), finished);
assert.throws(()=>sim.start_episode(JSON.stringify({ start: episode.start })));
assert.throws(()=>sim.start_episode(JSON.stringify({ ...episode, map: 'other-map' })));
assert.throws(()=>sim.start_episode(JSON.stringify({ ...episode, unknown: 1 })));
assert.throws(()=>sim.sample_episode(JSON.stringify({ min_distance: 1 })));
sim.start_episode(JSON.stringify(episode));
assert.throws(()=>sim.decide(9));
sim.reset();
assert.equal(JSON.parse(sim.episode_state()), null);
// Live session: place_random, then retarget from the current state.
sim.set_vehicle('car', 'coal');
const placed = JSON.parse(sim.place_random(7));
assert.deepEqual(JSON.parse(sim.place_random(7)), placed);
const placedState = JSON.parse(sim.vehicle_state());
assert.deepEqual([placedState.x, placedState.y, placedState.orientation], [placed.x, placed.y, placed.orientation]);
assert.equal(placedState.speed, 0);
assert.equal(placedState.health, 450);
assert.equal(JSON.parse(sim.episode_state()), null);
assert.equal(JSON.parse(sim.target_state()), null);
sim.sample_episode(sampleRequest);
for (let i = 0; i < 8; i++) sim.decide(7);
const driving = sim.vehicle_state();
assert.ok(JSON.parse(driving).speed > 0);
const live = JSON.parse(sim.retarget(episode.start.x, episode.start.y));
assert.equal(live.reachable, true);
assert.equal(sim.vehicle_state(), driving);
assert.deepEqual([live.start.x, live.start.y], [JSON.parse(driving).x, JSON.parse(driving).y]);
assert.equal(live.mode, 'reactive');
const liveState = JSON.parse(sim.episode_state());
assert.deepEqual([liveState.status, liveState.ticks, liveState.decisions, liveState.prev_action], ['running', 0, 0, null]);
assert.equal(liveState.optimal_distance, live.optimal_distance);
assert.equal(live.time_limit_ticks, Math.ceil(live.time_limit.base_ticks + live.time_limit.per_tile_ticks * live.optimal_distance));
assert.equal(JSON.parse(sim.target_state()).x, episode.start.x);
const timeFraction = rlSpec.vector_features.indexOf('time_fraction');
assert.equal(sim.policy_vector()[timeFraction], 0);
assert.ok(JSON.parse(sim.distance_field()).width > 0);
let liveDecision;
waypoints = sim.baseline_path();
for (let i = 0; i < 2000; i++) {
  liveDecision = JSON.parse(sim.follow_path(waypoints));
  if (liveDecision.done) break;
  if (liveDecision.replan) waypoints = sim.baseline_path();
}
assert.equal(liveDecision.status, 'success');
const reached = sim.episode_state();
assert.deepEqual(JSON.parse(sim.retarget(10000, 0)), { reachable: false });
assert.equal(sim.episode_state(), reached);
assert.throws(()=>sim.retarget(0, 0, 3, JSON.stringify({ unknown: 1 })));
assert.equal(JSON.parse(sim.retarget(episode.target.x, episode.target.y, 2, JSON.stringify({ mode: 'direct_plan' }))).mode, 'direct_plan');
assert.equal(JSON.parse(sim.target_state()).radius, 2);
sim.set_vehicle('tank', 'coal');
const tankPose = JSON.parse(sim.place_random(11));
const tankState = JSON.parse(sim.vehicle_state());
assert.deepEqual([tankState.kind, tankState.x, tankState.y, tankState.health, tankState.speed], ['tank', tankPose.x, tankPose.y, 2000, 0]);

twin.free();
sim.free();
console.log(`Wasm API smoke check passed: constructor and map loading, typed arrays, palettes, determinism, lifecycle, input errors and RL episodes (baseline drove ${actions.length} decisions to success, replay matched), live retarget and place_random. Map load ${loadMs.toFixed(2)} ms, ${entities.length} entities.`);

const fingerprint = bytes => bytes.reduce((hash, byte) => Math.imul(hash ^ byte, 16777619) >>> 0, 2166136261).toString(16).padStart(8,'0');
console.log(`Map fingerprints: tiles ${fingerprint(tiles)}, resources ${fingerprint(resources)}.`);
